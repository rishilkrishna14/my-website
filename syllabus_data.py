# Helper function to get available boards, classes, subjects, chapters
def get_curriculum_tree():
    tree = {}
    for board, classes in SYLLABUS.items():
        tree[board] = {}
        for cls, subjects in classes.items():
            tree[board][cls] = {}
            for sub, chapters in subjects.items():
                tree[board][cls][sub] = list(chapters.keys())
    return tree

# Function to fetch questions filtered by board, class, subject, chapter, type, difficulty
def get_questions(board, grade, subject, chapter=None, game_type="all", difficulty="all", limit=5):
    import random
    
    # Fallback to CBSE if board not found
    b_data = SYLLABUS.get(board, SYLLABUS["CBSE"])
    # Fallback to available class if grade not found
    c_data = b_data.get(str(grade))
    if not c_data:
        avail_grades = list(b_data.keys())
        c_data = b_data[avail_grades[0]]
        
    # Fallback to first available subject if subject not found
    if subject not in c_data:
        subject = list(c_data.keys())[0]
    sub_data = c_data[subject]
    
    questions = []
    if chapter and chapter in sub_data:
        questions = list(sub_data[chapter])
    else:
        # Combine all chapters of this subject
        for ch, q_list in sub_data.items():
            questions.extend(q_list)
            
    filtered = []
    for q in questions:
        if game_type != "all" and q.get("type") != game_type:
            continue
        if difficulty != "all" and q.get("difficulty") != difficulty:
            continue
        filtered.append(q)
        
    # If filtered is empty because of strict filters, fallback to all questions in that subject
    if not filtered:
        filtered = questions
        
    random.shuffle(filtered)
    return filtered[:limit]


