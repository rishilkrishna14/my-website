def get_subtopics(board, grade, subject, chapter):
    if chapter in CHAPTER_SUBTOPICS_MAP:
        return CHAPTER_SUBTOPICS_MAP[chapter]
    for ch, subs in CHAPTER_SUBTOPICS_MAP.items():
        if chapter and (chapter.lower() in ch.lower() or ch.lower() in chapter.lower()):
            return subs
    return [
        "All Subtopics (Full Chapter)",
        "1.1 Fundamental Definitions & Key Principles",
        "1.2 Textbook Worked Examples & Laws",
        "1.3 Concept Exercises & Review Questions"
    ]

def get_chapter_pdf_data(board, grade, subject, chapter, subtopic=None):
    res_data = None
    if chapter and chapter in STATE_BOARD_TEXTBOOK_CHAPTER_PDFS:
        res_data = dict(STATE_BOARD_TEXTBOOK_CHAPTER_PDFS[chapter])
    else:
        for ch_name, data in STATE_BOARD_TEXTBOOK_CHAPTER_PDFS.items():
            if chapter and (chapter.lower() in ch_name.lower() or ch_name.lower() in chapter.lower()):
                res_data = dict(data)
                break
                
    if not res_data:
        ch_display = chapter if chapter else subject
        pdf_base = "https://www.tntextbooks.in/p/6th-books.html" if str(grade) == "6" else ("https://www.tntextbooks.in/p/7th-books.html" if str(grade) == "7" else "https://www.tntextbooks.in/p/8th-standard.html")
        res_data = {
            "title": f"Chapter: {ch_display}",
            "book_title": f"Tamil Nadu State Board Class {grade} {subject} (English Medium)",
            "term": f"Samacheer Kalvi Class {grade}",
            "units": f"Class {grade} {subject}",
            "pages": "Full Chapter",
            "pdf_url": pdf_base,
            "gov_url": "https://textbooksonline.tn.nic.in/",
            "sections": [
                {
                    "heading": f"{ch_display} - Textbook Study Chapter",
                    "text": f"This official chapter from the Tamil Nadu State Board (English Medium) Class {grade} {subject} textbook covers foundational concepts, diagrams, scientific laws, and practical applications. Read this textbook section thoroughly before proceeding to the practice battle."
                }
            ]
        }
    else:
        # Clone sections
        res_data["sections"] = list(res_data["sections"])

    # If subtopic selected and not 'All Subtopics'
    if subtopic and "all subtopics" not in subtopic.lower():
        res_data["subtopic_selected"] = subtopic
        res_data["title"] = f"{res_data['title']} • {subtopic}"
        
        # Check if any section matches this subtopic
        matched_sections = [s for s in res_data["sections"] if subtopic.lower() in s["heading"].lower() or any(w.lower() in s["heading"].lower() for w in subtopic.split()[1:3])]
        if matched_sections:
            res_data["sections"] = matched_sections
            
    return res_data



